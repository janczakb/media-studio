# FLEX Media Studio

Media Studio is an independent Laravel library; Filament, FLEX Fields, Laravel AI,
MCP and Spatie Media Library are optional adapters. Before adding a picker,
upload/editor integration, thumbnails, sharing, AI, search, tenant scoping or
keyboard behavior, activate the `media-studio-development` skill. Follow its
installed-version API references rather than inventing methods or storage paths.

Keep durable media references separate from signed URLs. Selecting existing media
reuses its identity without uploading its bytes again. Resolve the principal,
tenant, workspace and source policy server-side. Use indexed cursor pagination,
bounded background processing and small ready renditions in file lists. Never
scan a storage bucket, generate previews or send paid AI requests merely to
render a list. Do not enable optional capabilities or publish assets without the
host application's intended configuration and authorization.
