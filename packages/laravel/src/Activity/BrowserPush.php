<?php

declare(strict_types=1);

namespace UseFlex\MediaStudio\Activity;

use GuzzleHttp\Client;
use Illuminate\Support\Facades\DB;
use Minishlink\WebPush\WebPush;
use UseFlex\MediaStudio\Identity\Principal;

final class BrowserPush
{
    public const EVENTS = ['mentioned', 'uploaded', 'guest_uploaded', 'processed', 'trashed', 'restored', 'purged'];

    public const DEVICE_LIMIT = 10;

    private const DEFAULT_EVENTS = ['mentioned', 'guest_uploaded', 'processed'];

    public static function enabled(): bool
    {
        return config('media-studio.notifications.enabled', true) && config('media-studio.notifications.push.enabled', false);
    }

    public static function available(): bool
    {
        return self::enabled() && class_exists(WebPush::class) && class_exists(Client::class)
            && self::key((string) config('media-studio.notifications.push.public_key'), 65, "\x04")
            && self::key((string) config('media-studio.notifications.push.private_key'), 32)
            && preg_match('~\A(?:mailto:|https://)[^\s]+\z~', (string) config('media-studio.notifications.push.subject')) === 1;
    }

    public static function key(string $value, int $size, string $prefix = ''): bool
    {
        if (! preg_match('/\A[A-Za-z0-9_-]+\z/', $value)) {
            return false;
        }

        $bytes = base64_decode(strtr($value, '-_', '+/'), true);

        return $bytes !== false && strlen($bytes) === $size && str_starts_with($bytes, $prefix)
            && rtrim(strtr(base64_encode($bytes), '+/', '-_'), '=') === $value;
    }

    public static function acceptsEndpoint(string $endpoint): bool
    {
        if (preg_match('~\Ahttps://([a-z0-9.-]+)(/[^\s\\\\#]*)\z~D', $endpoint, $parts) !== 1) {
            return false;
        }

        $host = $parts[1];

        return in_array($host, ['fcm.googleapis.com', 'updates.push.services.mozilla.com', 'web.push.apple.com'], true)
            || str_ends_with($host, '.push.apple.com')
            || str_ends_with($host, '.notify.windows.com');
    }

    /** @return list<string> */
    public static function events(int $workspace, string $principal): array
    {
        $events = DB::table('fms_push_preferences')->where('workspace_id', $workspace)
            ->where('principal_key', $principal)->value('events');

        return $events === null ? self::DEFAULT_EVENTS : json_decode($events, true, flags: JSON_THROW_ON_ERROR);
    }

    /** @param list<string> $notificationIds Only IDs generated by the current inbox insertion. */
    public function enqueue(object $workspace, Principal $principal, string $event, array $notificationIds): void
    {
        if (! self::enabled()) {
            return;
        }

        $devices = DB::table('fms_push_devices')->where('principal_key', $principal->key())
            ->orderBy('id')->limit(self::DEVICE_LIMIT)->pluck('id');
        if ($devices->isEmpty() || ! in_array($event, self::events((int) $workspace->id, $principal->key()), true)) {
            return;
        }

        $notifications = DB::table('fms_notifications')->where('workspace_id', $workspace->id)
            ->where('principal_key', $principal->key())->whereIn('public_id', $notificationIds)->pluck('id');
        $now = now();
        $expires = $now->copy()->addHours(6);
        $rows = [];
        foreach ($notifications as $notification) {
            foreach ($devices as $device) {
                $rows[] = [
                    'notification_id' => $notification, 'device_id' => $device,
                    'principal_type' => $principal->type, 'principal_id' => $principal->id,
                    'available_at' => $now, 'expires_at' => $expires,
                ];
            }
        }

        foreach (array_chunk($rows, 100) as $batch) {
            DB::table('fms_push_deliveries')->insertOrIgnore($batch);
        }
    }
}
